const TaskBankSem2 = {
  tasks: TASK_BANK_SEM2,

  /**
   * Возвращает ровно 6 задач (по 1 из каждой из 6 категорий)
   */
  getRandomTasks() {
    const selected = [];
    for (let cat = 1; cat <= 6; cat++) {
      const catTasks = this.tasks.filter(t => t.category === cat);
      if (catTasks.length > 0) {
        const randomIndex = Math.floor(Math.random() * catTasks.length);
        selected.push(catTasks[randomIndex]);
      }
    }
    return selected;
  },

  /**
   * Парсинг числового ввода студента
   */
  parseNumericInput(val) {
    if (val === null || val === undefined) return NaN;
    const cleanStr = String(val).trim().replace(',', '.').replace(/\s+/g, '');
    const num = parseFloat(cleanStr);
    return isNaN(num) ? NaN : num;
  },

  /**
   * Валидация ответа студента с учетом допуска
   */
  validateAnswer(taskOrId, userAnswer) {
    const task = typeof taskOrId === 'string' ? this.getTaskById(taskOrId) : taskOrId;
    if (!task) return false;

    const userVal = this.parseNumericInput(userAnswer);
    if (isNaN(userVal)) return false;

    const expected = task.correctAnswer;
    const tolPercent = task.tolerancePercent || 1.5;

    // Для нулевых ответов абсолютный допуск
    if (Math.abs(expected) < 1e-7) {
      return Math.abs(userVal) <= 0.05;
    }

    const delta = Math.abs(userVal - expected);
    const maxAllowedDelta = Math.abs(expected) * (tolPercent / 100);

    return delta <= maxAllowedDelta;
  },

  getTaskById(id) {
    return this.tasks.find(t => t.id === id);
  },

  getAllTasks() {
    return this.tasks;
  },

  getTasksByCategory(category) {
    return this.tasks.filter(t => t.category === category);
  }
};

