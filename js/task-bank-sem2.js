  /**
   * Возвращает ровно 4 задачи (по 1 из каждой из 4 категорий)
   */
  getRandomTasks() {
    const selected = [];
    for (let cat = 1; cat <= 4; cat++) {
      const catTasks = this.tasks.filter(t => t.category === cat);
      if (catTasks.length > 0) {
        const randomIndex = Math.floor(Math.random() * catTasks.length);
        selected.push(catTasks[randomIndex]);
      }
    }
    return selected;
  },

  /**
   * Парсинг числового ввода студента
   */
  parseNumericInput(val) {
    if (val === null || val === undefined) return NaN;
    const cleanStr = String(val).trim().replace(',', '.').replace(/\s+/g, '');
    const num = parseFloat(cleanStr);
    return isNaN(num) ? NaN : num;
  },

